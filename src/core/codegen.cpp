std::string generate_loader_header(const GenInfo& info) {
    std::string out = kS3PackTemplate;
    out = replace_all(out, "@TOOL_VERSION@", info.tool_version);
    out = replace_all(out, "@LAYOUT_SIGNATURE@", info.layout.signature());
    out = replace_all(out, "@MAGIC@", info.layout.magic_string());
    out = replace_all(out, "@PACK_EXT@", info.layout.extension);
    out = replace_all(out, "@VERSION_MAJOR@", std::to_string(kPackVersionMajor));
    out = replace_all(out, "@VERSION_MINOR@", std::to_string(kPackVersionMinor));
    return out;
}


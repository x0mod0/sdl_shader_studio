std::string generate_id_header(const std::vector<PackShader>& shaders, const GenInfo& info) {
    std::ostringstream os;
    const std::string guard =
        "SSSTUDIO_" + replace_all(info.enum_prefix, "-", "_") + "_IDS_H_INCLUDED";

    os << banner(info, "shader ids") << "#ifndef " << guard << "\n#define " << guard << "\n\n";
    os << "#include <SDL3/SDL_stdinc.h>\n\n";

    if (!info.cpp_namespace.empty()) os << "#ifdef __cplusplus\nnamespace " << info.cpp_namespace << " {\n#endif\n\n";

    os << "/* Shader ids. Keys are " << to_string(KeyStrategy::Explicit)
       << "-stable: once assigned they are pinned in project.toml and never move. */\n";
    os << "typedef enum " << info.enum_prefix << "_Id {\n";

    std::vector<const PackShader*> sorted;
    for (const auto& s : shaders) sorted.push_back(&s);
    std::sort(sorted.begin(), sorted.end(),
              [](const PackShader* a, const PackShader* b) { return a->id < b->id; });

    std::size_t width = 0;
    for (const auto* s : sorted) width = std::max(width, enum_name(info.enum_prefix, s->id).size());

    for (const auto* s : sorted) {
        const std::string name = enum_name(info.enum_prefix, s->id);
        os << "    " << name << std::string(width - name.size(), ' ') << " = " << hex32(s->key)
           << ",  /* " << to_string(s->stage) << ", entry '" << s->entry_point << "' */\n";
    }
    os << "    " << info.enum_prefix << "_COUNT = " << shaders.size() << "\n";
    os << "} " << info.enum_prefix << "_Id;\n\n";

    os << "/* Per-shader resource counts, so a pipeline can be sized at compile time. */\n";
    for (const auto* s : sorted) {
        const std::string n = enum_name(info.enum_prefix, s->id);
        const bool compute = s->stage == Stage::Compute;
        const std::uint32_t ro_tex = compute ? s->reflection.num_readonly_storage_textures()
                                             : s->reflection.num_storage_textures();
        const std::uint32_t ro_buf = compute ? s->reflection.num_readonly_storage_buffers()
                                             : s->reflection.num_storage_buffers();
        os << "#define " << n << "_NUM_SAMPLERS " << s->reflection.num_samplers() << "\n";
        os << "#define " << n << "_NUM_STORAGE_TEXTURES " << ro_tex << "\n";
        os << "#define " << n << "_NUM_STORAGE_BUFFERS " << ro_buf << "\n";
        os << "#define " << n << "_NUM_UNIFORM_BUFFERS " << s->reflection.num_uniform_buffers()
           << "\n";
        if (compute) {
            os << "#define " << n << "_NUM_RW_STORAGE_TEXTURES "
               << s->reflection.num_readwrite_storage_textures() << "\n";
            os << "#define " << n << "_NUM_RW_STORAGE_BUFFERS "
               << s->reflection.num_readwrite_storage_buffers() << "\n";
            os << "#define " << n << "_THREADS_X " << s->reflection.compute_threads[0] << "\n";
            os << "#define " << n << "_THREADS_Y " << s->reflection.compute_threads[1] << "\n";
            os << "#define " << n << "_THREADS_Z " << s->reflection.compute_threads[2] << "\n";
        }
        os << "\n";
    }

    os << "#define " << info.enum_prefix << "_PACK_FILE \"" << info.pack_filename << "\"\n";
    os << "#define " << info.enum_prefix << "_PACK_FORMATS "
       << hex32(info.stats.format_mask) << "\n";
    os << "#define " << info.enum_prefix << "_PACK_LAYOUT \"" << info.layout.signature() << "\"\n";

    if (!info.cpp_namespace.empty()) os << "\n#ifdef __cplusplus\n}  /* namespace */\n#endif\n";
    os << "\n#endif /* " << guard << " */\n";
    return os.str();
}


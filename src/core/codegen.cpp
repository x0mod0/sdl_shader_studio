std::string generate_meta_toml(const std::vector<PackShader>& shaders, const GenInfo& info) {
    std::ostringstream os;
    os << "# Build provenance for " << info.pack_filename << ".\n"
       << "# This file is optional at runtime. If you ship it, every field here is yours to\n"
       << "# edit or extend - the loader never reads it unless you ask it to.\n\n";
    os << "[build]\n";
    os << "tool = \"" << info.tool_version << "\"\n";
    os << "project = \"" << info.project_name << "\"\n";
    os << "profile = \"" << info.profile_name << "\"\n";
    os << "time = \"" << info.build_time << "\"\n";
    os << "formats = \"" << format_mask_to_string(info.stats.format_mask) << "\"\n";
    os << "compression = \"" << to_string(info.compression) << "\"\n";
    os << "total_bytes = " << info.stats.total_bytes << "\n";
    if (!info.defines.empty()) {
        os << "defines = [";
        for (std::size_t i = 0; i < info.defines.size(); ++i) {
            if (i) os << ", ";
            os << "\"" << info.defines[i] << "\"";
        }
        os << "]\n";
    }
    os << "\n[layout]\n";
    os << "signature = \"" << info.layout.signature() << "\"\n";
    os << "magic = \"" << info.layout.magic_string() << "\"\n";
    os << "extension = \"" << info.layout.extension << "\"\n";
    os << "header_preset = \"" << to_string(info.layout.header_preset) << "\"\n";
    os << "entry_sort = \"" << to_string(info.layout.entry_sort) << "\"\n";
    os << "alignment = " << info.layout.alignment << "\n";
    os << "key_bits = " << (info.layout.key16 ? 16 : 32) << "\n\n";

    for (const auto& s : shaders) {
        os << "[[shader]]\n";
        os << "id = \"" << s.id << "\"\n";
        os << "key = " << s.key << "\n";
        os << "enum = \"" << enum_name(info.enum_prefix, s.id) << "\"\n";
        os << "stage = \"" << to_string(s.stage) << "\"\n";
        os << "language = \"" << to_string(s.language) << "\"\n";
        os << "entry = \"" << s.entry_point << "\"\n";
        if (s.stage == Stage::Compute) {
            os << "threads = [" << s.reflection.compute_threads[0] << ", "
               << s.reflection.compute_threads[1] << ", " << s.reflection.compute_threads[2]
               << "]\n";
        }
        os << "\n";
    }
    return os.str();
}

std::string generate_reflection_json(const std::vector<PackShader>& shaders) {
    std::ostringstream os;
    os << "{\n  \"shaders\": [\n";
    for (std::size_t i = 0; i < shaders.size(); ++i) {
        os << "    {\"id\":\"" << shaders[i].id << "\",\"key\":" << shaders[i].key
           << ",\"reflection\":" << reflection_to_json(shaders[i].reflection) << "}";
        if (i + 1 < shaders.size()) os << ",";
        os << "\n";
    }
    os << "  ]\n}\n";
    return os.str();
}

std::string generate_cmake_snippet(const GenInfo& info) {
    std::ostringstream os;
    os << "# Rebuilds the shader pack whenever a source shader changes.\n"
       << "# add_shader_pack(TARGET my_game PROJECT ${CMAKE_SOURCE_DIR}/shaders/MyShaders.ssstudio)\n\n"
       << "find_program(SSSTUDIO_CLI ssstudio REQUIRED)\n\n"
       << "function(add_shader_pack)\n"
       << "    cmake_parse_arguments(ARG \"\" \"TARGET;PROJECT;PROFILE;OUTPUT\" \"\" ${ARGN})\n"
       << "    if(NOT ARG_PROFILE)\n        set(ARG_PROFILE \"" << info.profile_name << "\")\n    endif()\n"
       << "    if(NOT ARG_OUTPUT)\n        set(ARG_OUTPUT \"${CMAKE_CURRENT_BINARY_DIR}/shaders\")\n    endif()\n"
       << "    file(GLOB_RECURSE SHADER_SOURCES \"${ARG_PROJECT}/shaders/*\")\n"
       << "    add_custom_command(\n"
       << "        OUTPUT \"${ARG_OUTPUT}/" << info.pack_filename << "\"\n"
       << "        COMMAND ${SSSTUDIO_CLI} build \"${ARG_PROJECT}\" --profile ${ARG_PROFILE} --out \"${ARG_OUTPUT}\"\n"
       << "        DEPENDS ${SHADER_SOURCES} \"${ARG_PROJECT}/project.toml\"\n"
       << "        COMMENT \"Building shader pack\"\n"
       << "        VERBATIM)\n"
       << "    add_custom_target(${ARG_TARGET}_shaders DEPENDS \"${ARG_OUTPUT}/"
       << info.pack_filename << "\")\n"
       << "    add_dependencies(${ARG_TARGET} ${ARG_TARGET}_shaders)\n"
       << "    target_include_directories(${ARG_TARGET} PRIVATE \"${ARG_OUTPUT}\")\n"
       << "endfunction()\n";
    return os.str();
}


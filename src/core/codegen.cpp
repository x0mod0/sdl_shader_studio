std::string generate_embed_header(const std::vector<std::uint8_t>& pack, const GenInfo& info) {
    std::ostringstream os;
    const std::string sym = replace_all(info.enum_prefix, "-", "_");
    os << banner(info, "embedded pack")
       << "#ifndef SSSTUDIO_" << sym << "_EMBED_H_INCLUDED\n#define SSSTUDIO_" << sym
       << "_EMBED_H_INCLUDED\n\n#include <SDL3/SDL_stdinc.h>\n\n";
    os << "static const Uint8 " << sym << "_PACK_BYTES[" << pack.size() << "] = {\n";
    os << std::hex << std::setfill('0');
    for (std::size_t i = 0; i < pack.size(); ++i) {
        if (i % 16 == 0) os << "    ";
        os << "0x" << std::setw(2) << static_cast<int>(pack[i]);
        if (i + 1 < pack.size()) os << ",";
        if (i % 16 == 15 || i + 1 == pack.size()) os << "\n";
        else os << " ";
    }
    os << std::dec;
    os << "};\n\n#define " << sym << "_PACK_SIZE " << pack.size() << "u\n\n";
    os << "#endif\n";
    return os.str();
}


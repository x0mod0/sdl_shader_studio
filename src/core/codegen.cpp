std::string replace_all(std::string s, const std::string& from, const std::string& to) {
    if (from.empty()) return s;
    std::size_t pos = 0;
    while ((pos = s.find(from, pos)) != std::string::npos) {
        s.replace(pos, from.size(), to);
        pos += to.size();
    }
    return s;
}

std::string hex32(std::uint32_t v) {
    std::ostringstream os;
    os << "0x" << std::hex << std::uppercase << std::setw(8) << std::setfill('0') << v << "u";
    return os.str();
}

std::string banner(const GenInfo& info, const char* file_kind) {
    std::ostringstream os;
    os << "// " << file_kind << " - generated by " << info.tool_version << "\n"
       << "// project: " << info.project_name << "   profile: " << info.profile_name << "\n"
       << "// pack:    " << info.pack_filename << "   layout: " << info.layout.signature() << "\n"
       << "// Do not edit by hand; rebuild instead (or take ownership and stop regenerating).\n";
    return os.str();
}

// C type for a uniform member, with the padding rules HLSL/std140 imply.
struct StructField {
    std::string type;
    std::string name;
    std::uint32_t offset;
    std::uint32_t size;
};

std::string c_scalar(ScalarType t) {
    switch (t) {
        case ScalarType::Bool: return "Sint32";  // HLSL bool is 4 bytes in a cbuffer
        case ScalarType::Int: return "Sint32";
        case ScalarType::UInt: return "Uint32";
        case ScalarType::Double: return "double";
        default: return "float";
    }
}

std::string c_member_type(const UniformMember& m) {
    const std::string base = c_scalar(m.type);
    if (m.rows > 1) return base;  // matrices are emitted as arrays below
    if (m.cols > 1) return base;
    return base;
}

std::string c_member_decl(const UniformMember& m) {
    const std::string base = c_member_type(m);
    std::string decl = base + " " + m.name;
    const std::uint32_t comps = m.rows * m.cols;
    if (comps > 1) decl += "[" + std::to_string(comps) + "]";
    if (m.array_size > 0) decl += "[" + std::to_string(m.array_size) + "]";
    return decl;
}


std::string generate_docs(const std::vector<PackShader>& shaders, const GenInfo& info) {
    std::ostringstream os;
    const bool compute_only = info.stats.compute_only;

    os << "# " << info.project_name << " - shader pack\n\n";
    os << "Generated by " << info.tool_version << " (profile `" << info.profile_name << "`) on "
       << info.build_time << ".\n\n";

    os << "| | |\n|---|---|\n";
    os << "| Pack file | `" << info.pack_filename << "` |\n";
    os << "| Shaders | " << shaders.size() << " |\n";
    os << "| Formats | " << format_mask_to_string(info.stats.format_mask) << " |\n";
    os << "| Compression | " << to_string(info.compression) << " |\n";
    os << "| Size | " << info.stats.total_bytes << " bytes (from "
       << info.stats.raw_bytes << " raw) |\n";
    os << "| Layout | `" << info.layout.signature() << "` |\n";
    if (compute_only) os << "| Kind | compute-only pack |\n";
    os << "\n";

    os << "## Loading\n\n";
    os << "```c\n#define S3PACK_IMPLEMENTATION\n#include \"s3pack.h\"\n#include \"shaders.h\"\n\n"
       << "S3PACK_Pack pack;\nif (!S3PACK_OpenFile(&pack, \"" << info.pack_filename
       << "\")) {\n    SDL_Log(\"%s\", S3PACK_GetError());\n}\n```\n\n";
    os << "```cpp\n// C++: the pack, shaders and pipelines release themselves.\n"
       << "auto pack = s3pack::Pack::open_file(\"" << info.pack_filename << "\");\n"
       << "if (!pack) SDL_Log(\"%s\", pack.error());\n```\n\n";
    // Only warn when compression was actually applied: below the threshold every
    // blob is stored raw, and a note telling the reader to define a decoder macro
    // they do not need would be wrong.
    const bool actually_compressed =
        info.compression != Compression::None && info.stats.stored_bytes < info.stats.raw_bytes;
    if (actually_compressed) {
        os << "> This pack is " << to_string(info.compression)
           << " compressed. Define `S3PACK_"
           << (info.compression == Compression::LZ4 ? "LZ4" : "ZSTD")
           << "_DECODE` before including `s3pack.h`, or rebuild with `compression = \"none\"`.\n\n";
    }

    os << "## Shaders\n\n";
    os << "| Id | Key | Stage | Entry | Language | Formats |\n|---|---|---|---|---|---|\n";
    std::vector<const PackShader*> sorted;
    for (const auto& s : shaders) sorted.push_back(&s);
    std::sort(sorted.begin(), sorted.end(),
              [](const PackShader* a, const PackShader* b) { return a->id < b->id; });
    for (const auto* s : sorted) {
        std::uint32_t mask = 0;
        for (const auto& [fmt, bytes] : s->blobs) {
            (void)bytes;
            mask |= fmt;
        }
        os << "| `" << enum_name(info.enum_prefix, s->id) << "` | " << hex32(s->key) << " | "
           << to_string(s->stage) << " | `" << s->entry_point << "` | " << to_string(s->language)
           << " | " << format_mask_to_string(mask) << " |\n";
    }
    os << "\n";

    for (const auto* sp : sorted) {
        const PackShader& s = *sp;
        const bool compute = s.stage == Stage::Compute;
        os << "---\n\n### " << s.id << "\n\n";
        os << "`" << enum_name(info.enum_prefix, s.id) << "` = " << hex32(s.key) << " - "
           << to_string(s.stage) << ", entry `" << s.entry_point << "`";
        if (compute) {
            os << ", thread group " << s.reflection.compute_threads[0] << "x"
               << s.reflection.compute_threads[1] << "x" << s.reflection.compute_threads[2];
        }
        os << ".\n\n";

        if (const auto it = info.provenance.find(s.id); it != info.provenance.end()) {
            const Provenance& origin = it->second;
            os << "> Imported";
            if (!origin.author.empty()) os << " - by " << origin.author;
            if (!origin.imported.empty()) os << " on " << origin.imported;
            os << ".\n";
            if (!origin.url.empty()) os << "> Source: <" << origin.url << ">\n";
            if (!origin.licence.empty()) os << "> Licence: " << origin.licence << "\n";
            os << "\n";
        }

        os << "Create-info counts: samplers " << s.reflection.num_samplers()
           << ", storage textures "
           << (compute ? s.reflection.num_readonly_storage_textures()
                       : s.reflection.num_storage_textures())
           << ", storage buffers "
           << (compute ? s.reflection.num_readonly_storage_buffers()
                       : s.reflection.num_storage_buffers())
           << ", uniform buffers " << s.reflection.num_uniform_buffers();
        if (compute) {
            os << ", read-write textures " << s.reflection.num_readwrite_storage_textures()
               << ", read-write buffers " << s.reflection.num_readwrite_storage_buffers();
        }
        os << ".\n\n";

        if (!s.reflection.resources.empty()) {
            os << "**Resources**\n\n| Name | Kind | Space/Set | Register | Notes |\n"
                  "|---|---|---|---|---|\n";
            for (const auto& r : s.reflection.resources) {
                os << "| `" << r.name << "` | " << to_string(r.kind) << " | " << r.set << " | "
                   << r.binding << " | " << to_string(r.dim);
                if (r.writable) os << ", read-write";
                if (r.struct_stride) os << ", stride " << r.struct_stride;
                os << " |\n";
            }
            os << "\n";
        }

        if (!s.reflection.uniform_blocks.empty()) {
            os << "**Uniform buffers**\n\n| Block | Space/Set | Register | Size | Members |\n"
                  "|---|---|---|---|---|\n";
            for (const auto& b : s.reflection.uniform_blocks) {
                os << "| `" << b.name << "` | " << b.set << " | b" << b.binding << " | " << b.size
                   << " B | ";
                for (std::size_t i = 0; i < b.members.size(); ++i) {
                    if (i) os << ", ";
                    os << "`" << b.members[i].c_type() << " " << b.members[i].name << "`";
                }
                os << " |\n";
            }
            os << "\n```c\n" << snippet_uniform_struct(s) << "\n```\n\n";
            os << "```c\n" << snippet_uniform_push(s) << "\n```\n\n";
        }

        if (!compute && !s.reflection.vertex_inputs.empty()) {
            os << "**Vertex inputs**\n\n| Location | Name | Semantic | Suggested format |\n"
                  "|---|---|---|---|\n";
            auto vi = s.reflection.vertex_inputs;
            std::sort(vi.begin(), vi.end(),
                      [](const VertexInput& a, const VertexInput& b) { return a.location < b.location; });
            for (const auto& v : vi) {
                os << "| " << v.location << " | `" << v.name << "` | "
                   << (v.semantic.empty() ? "-" : v.semantic) << " | `" << v.sdl_vertex_format()
                   << "` |\n";
            }
            os << "\n```c\n" << snippet_vertex_input_state(s, info) << "\n```\n\n";
        }

        os << "**Create (C)**\n\n```c\n" << snippet_create_shader(s, info, SnippetFlavor::C)
           << "\n```\n\n";
        os << "**Create (C++)**\n\n```cpp\n"
           << snippet_create_shader(s, info, SnippetFlavor::CppRaii) << "\n```\n\n";

        if (compute) {
            os << "**Dispatch**\n\n```c\n"
               << snippet_compute_dispatch(s, info, SnippetFlavor::C) << "\n```\n\n";
            os << "```cpp\n" << snippet_compute_dispatch(s, info, SnippetFlavor::CppRaii)
               << "\n```\n\n";
        }

        const std::string samplers = snippet_samplers(s);
        if (samplers.rfind("/*", 0) != 0) {
            os << "**Samplers**\n\n```c\n" << samplers << "\n```\n\n";
        }
    }

    // Pipeline example pairs the first vertex/fragment shaders it finds.
    if (!compute_only) {
        const PackShader* vs = nullptr;
        const PackShader* fs = nullptr;
        for (const auto* s : sorted) {
            if (!vs && s->stage == Stage::Vertex) vs = s;
            if (!fs && s->stage == Stage::Fragment) fs = s;
        }
        if (vs && fs) {
            os << "---\n\n## Pipeline example\n\n```c\n"
               << snippet_pipeline(*vs, *fs, info, SnippetFlavor::C) << "\n```\n\n";
            os << "```cpp\n" << snippet_pipeline(*vs, *fs, info, SnippetFlavor::CppRaii)
               << "\n```\n";
        }
    }

    os << "\n---\n\n## Keys\n\nKeys are 32-bit values (never strings). This pack uses the `"
       << to_string(KeyStrategy::Explicit)
       << "` strategy by default: the first build derives a key with FNV-1a 32 of the shader id, "
          "pins it in `project.toml`, and never changes it again - so shipping a new pack to an "
          "old binary keeps working.\n";
    return os.str();
}


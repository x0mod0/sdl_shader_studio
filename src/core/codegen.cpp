std::string snippet_create_shader(const PackShader& s, const GenInfo& info, SnippetFlavor f) {
    const std::string id = enum_name(info.enum_prefix, s.id);
    std::ostringstream os;
    if (f == SnippetFlavor::C) {
        os << "SDL_GPUShader *" << s.id << " = S3PACK_CreateShader(device, &pack, " << id << ");\n"
           << "if (!" << s.id << ") { SDL_Log(\"%s\", S3PACK_GetError()); return false; }\n"
           << "/* release with SDL_ReleaseGPUShader(device, " << s.id << "); */";
    } else {
        os << "s3pack::Shader " << s.id << " = pack.shader(device, " << id << ");\n"
           << "if (!" << s.id << ") { SDL_Log(\"%s\", pack.error()); return false; }\n"
           << "/* released automatically when it goes out of scope */";
    }
    return os.str();
}

std::string snippet_vertex_input_state(const PackShader& s, const GenInfo& info) {
    (void)info;
    if (s.stage != Stage::Vertex || s.reflection.vertex_inputs.empty()) {
        return "/* no vertex inputs: draw with SDL_DrawGPUPrimitives and generate positions in the shader */";
    }
    auto inputs = s.reflection.vertex_inputs;
    std::sort(inputs.begin(), inputs.end(),
              [](const VertexInput& a, const VertexInput& b) { return a.location < b.location; });

    std::ostringstream os;
    std::uint32_t offset = 0;
    os << "/* Vertex layout derived from " << s.id << ". Offsets assume a tightly packed,\n"
       << "   interleaved buffer in location order; reorder if your vertex struct differs. */\n";
    os << "SDL_GPUVertexAttribute attributes[" << inputs.size() << "] = {\n";
    for (const auto& v : inputs) {
        const std::uint32_t size = v.components * 4;
        os << "    { .location = " << v.location << ", .buffer_slot = 0, .format = "
           << v.sdl_vertex_format() << ", .offset = " << offset << " },";
        if (!v.semantic.empty()) os << "  /* " << v.semantic << " " << v.name << " */";
        else os << "  /* " << v.name << " */";
        os << "\n";
        offset += size;
    }
    os << "};\n\n";
    os << "SDL_GPUVertexBufferDescription vertex_buffer = {\n"
       << "    .slot = 0,\n"
       << "    .pitch = " << offset << ",\n"
       << "    .input_rate = SDL_GPU_VERTEXINPUTRATE_VERTEX,\n"
       << "    .instance_step_rate = 0,\n};\n\n";
    os << "SDL_GPUVertexInputState vertex_input = {\n"
       << "    .vertex_buffer_descriptions = &vertex_buffer,\n"
       << "    .num_vertex_buffers = 1,\n"
       << "    .vertex_attributes = attributes,\n"
       << "    .num_vertex_attributes = SDL_arraysize(attributes),\n};";
    return os.str();
}

std::string snippet_pipeline(const PackShader& vs, const PackShader& fs, const GenInfo& info,
                             SnippetFlavor f) {
    std::ostringstream os;
    const std::string vget = f == SnippetFlavor::C ? vs.id : vs.id + ".get()";
    const std::string fget = f == SnippetFlavor::C ? fs.id : fs.id + ".get()";
    os << snippet_create_shader(vs, info, f) << "\n";
    os << snippet_create_shader(fs, info, f) << "\n\n";
    os << "SDL_GPUColorTargetDescription color_target = {\n"
       << "    .format = SDL_GetGPUSwapchainTextureFormat(device, window),\n"
       << "    .blend_state = { .enable_blend = false },\n};\n\n";
    os << "SDL_GPUGraphicsPipelineCreateInfo pipeline_info = {\n"
       << "    .vertex_shader = " << vget << ",\n"
       << "    .fragment_shader = " << fget << ",\n";
    if (!vs.reflection.vertex_inputs.empty()) os << "    .vertex_input_state = vertex_input,\n";
    os << "    .primitive_type = SDL_GPU_PRIMITIVETYPE_TRIANGLELIST,\n"
       << "    .rasterizer_state = { .fill_mode = SDL_GPU_FILLMODE_FILL,\n"
       << "                          .cull_mode = SDL_GPU_CULLMODE_NONE },\n"
       << "    .target_info = { .color_target_descriptions = &color_target,\n"
       << "                     .num_color_targets = 1 },\n};\n\n";
    os << "SDL_GPUGraphicsPipeline *pipeline = SDL_CreateGPUGraphicsPipeline(device, &pipeline_info);";
    return os.str();
}

std::string snippet_uniform_struct(const PackShader& s) {
    if (s.reflection.uniform_blocks.empty()) return "/* this shader declares no uniform buffers */";
    std::ostringstream os;
    for (const auto& b : s.reflection.uniform_blocks) {
        os << "/* " << b.name << " - space" << b.set << ", register b" << b.binding << ", "
           << b.size << " bytes.\n"
           << "   Field order and padding mirror the shader's constant buffer layout. */\n";
        os << "typedef struct " << b.name << " {\n";
        std::uint32_t cursor = 0;
        int pad_index = 0;
        for (const auto& m : b.members) {
            if (m.offset > cursor) {
                const std::uint32_t gap = m.offset - cursor;
                os << "    Uint8 _pad" << pad_index++ << "[" << gap << "];\n";
                cursor = m.offset;
            }
            os << "    " << c_member_decl(m) << ";";
            os << "  /* offset " << m.offset << ", " << m.size << " bytes */\n";
            cursor = m.offset + m.size;
        }
        if (b.size > cursor) {
            os << "    Uint8 _pad" << pad_index++ << "[" << (b.size - cursor) << "];\n";
        }
        os << "} " << b.name << ";\n\n";
        os << "SDL_COMPILE_TIME_ASSERT(" << b.name << "_size, sizeof(" << b.name
           << ") == " << b.size << ");\n\n";
    }
    std::string out = os.str();
    if (!out.empty() && out.back() == '\n') out.pop_back();
    return out;
}

std::string snippet_uniform_push(const PackShader& s) {
    if (s.reflection.uniform_blocks.empty()) return "/* this shader declares no uniform buffers */";
    std::ostringstream os;
    const char* fn = s.stage == Stage::Vertex     ? "SDL_PushGPUVertexUniformData"
                     : s.stage == Stage::Fragment ? "SDL_PushGPUFragmentUniformData"
                                                  : "SDL_PushGPUComputeUniformData";
    for (const auto& b : s.reflection.uniform_blocks) {
        const std::uint32_t slot = b.binding;
        os << b.name << " " << b.name << "_data = {0};\n";
        os << "/* fill fields here */\n";
        os << fn << "(command_buffer, " << slot << ", &" << b.name << "_data, sizeof("
           << b.name << "));\n";
    }
    std::string out = os.str();
    if (!out.empty() && out.back() == '\n') out.pop_back();
    return out;
}

std::string snippet_samplers(const PackShader& s) {
    std::vector<const Resource*> sampled;
    for (const auto& r : s.reflection.resources)
        if (r.kind == ResourceKind::SampledTexture) sampled.push_back(&r);
    if (sampled.empty()) return "/* this shader samples no textures */";

    std::ostringstream os;
    os << "SDL_GPUSamplerCreateInfo sampler_info = {\n"
       << "    .min_filter = SDL_GPU_FILTER_LINEAR,\n"
       << "    .mag_filter = SDL_GPU_FILTER_LINEAR,\n"
       << "    .mipmap_mode = SDL_GPU_SAMPLERMIPMAPMODE_LINEAR,\n"
       << "    .address_mode_u = SDL_GPU_SAMPLERADDRESSMODE_CLAMP_TO_EDGE,\n"
       << "    .address_mode_v = SDL_GPU_SAMPLERADDRESSMODE_CLAMP_TO_EDGE,\n"
       << "    .address_mode_w = SDL_GPU_SAMPLERADDRESSMODE_CLAMP_TO_EDGE,\n};\n"
       << "SDL_GPUSampler *sampler = SDL_CreateGPUSampler(device, &sampler_info);\n\n";
    os << "SDL_GPUTextureSamplerBinding bindings[" << sampled.size() << "] = {\n";
    for (const auto* r : sampled) {
        os << "    { .texture = /* " << r->name << " */ NULL, .sampler = sampler },  /* space"
           << r->set << ", t" << r->binding << " */\n";
    }
    os << "};\n";
    const char* bind = s.stage == Stage::Vertex     ? "SDL_BindGPUVertexSamplers"
                       : s.stage == Stage::Fragment ? "SDL_BindGPUFragmentSamplers"
                                                    : "SDL_BindGPUComputeSamplers";
    os << bind << "(render_pass, 0, bindings, SDL_arraysize(bindings));";
    return os.str();
}

std::string snippet_compute_dispatch(const PackShader& s, const GenInfo& info, SnippetFlavor f) {
    const std::string id = enum_name(info.enum_prefix, s.id);
    std::ostringstream os;
    const auto& t = s.reflection.compute_threads;
    if (f == SnippetFlavor::C) {
        os << "Uint32 threads[3];\n"
           << "SDL_GPUComputePipeline *pipeline =\n"
           << "    S3PACK_CreateComputePipeline(device, &pack, " << id << ", threads);\n\n"
           << "SDL_GPUComputePass *pass = SDL_BeginGPUComputePass(command_buffer,\n"
           << "                                                   storage_texture_bindings, 1,\n"
           << "                                                   storage_buffer_bindings, 0);\n"
           << "SDL_BindGPUComputePipeline(pass, pipeline);\n"
           << "SDL_DispatchGPUCompute(pass, (width + " << t[0] << " - 1) / " << t[0]
           << ",\n                            (height + " << t[1] << " - 1) / " << t[1] << ", 1);\n"
           << "SDL_EndGPUComputePass(pass);";
    } else {
        os << "s3pack::ComputePipeline " << s.id << " = pack.compute(device, " << id << ");\n\n"
           << "SDL_GPUComputePass *pass = SDL_BeginGPUComputePass(command_buffer,\n"
           << "                                                   storage_texture_bindings, 1,\n"
           << "                                                   storage_buffer_bindings, 0);\n"
           << "SDL_BindGPUComputePipeline(pass, " << s.id << ".get());\n"
           << "SDL_DispatchGPUCompute(pass, " << s.id << ".groups_for(width, 0),\n"
           << "                            " << s.id << ".groups_for(height, 1), 1);\n"
           << "SDL_EndGPUComputePass(pass);";
    }
    return os.str();
}

